void TestMaps::Load(const TestMap& _map, Grid& _grid)
{
	const int height = static_cast<int>(_map.rows.size());
	const int width = static_cast<int>(std::strlen(_map.rows.front()));
	_grid.Reset(width, height);

	// place endpoints first since walls can't go on the default ones
	GridPos start;
	GridPos end;

	for (int y = 0; y < height; ++y)
	{
		for (int x = 0; x < width; ++x)
		{
			if (_map.rows[y][x] == 'S')
			{
				start = { x, y };
			}
			else if (_map.rows[y][x] == 'E')
			{
				end = { x, y };
			}
		}
	}

	_grid.SetEndpoints(start, end);

	// then walls and costs
	for (int y = 0; y < height; ++y)
	{
		for (int x = 0; x < width; ++x)
		{
			const char symbol = _map.rows[y][x];

			if (symbol == '#')
			{
				_grid.SetWalkable({ x, y }, false);
			}
			else if (symbol >= '2' && symbol <= '9')
			{
				_grid.SetCost({ x, y }, static_cast<float>(symbol - '0'));
			}
		}
	}
}
